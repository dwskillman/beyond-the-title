#!/usr/bin/env node
// Dev-machine helper (optional, not part of using or publishing the site).
// Packs the open-licence Manrope font (SIL OFL 1.1) into site/css/fonts.css as WOFF data: URIs,
// so the site needs no font server and the lettering also works when opened from disk (file://),
// where Chrome blocks separate font files. Font data is not modified: each table is only zlib-compressed (WOFF 1.0).
//   node tests/make-font-css.mjs [fontDir]      (default fontDir: /Library/Fonts)
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2] || '/Library/Fonts';
const WEIGHTS = [[400, 'Regular'], [600, 'SemiBold'], [700, 'Bold'], [800, 'ExtraBold']];
const align4 = (n) => (n + 3) & ~3;

/** TrueType/OpenType (sfnt) → WOFF 1.0. Tables are copied byte-for-byte, compressed when that helps. */
export function ttfToWoff(ttf) {
  const numTables = ttf.readUInt16BE(4);
  const tables = [];
  for (let i = 0; i < numTables; i++) {
    const o = 12 + 16 * i;
    tables.push({ tag: ttf.subarray(o, o + 4), checksum: ttf.readUInt32BE(o + 4), offset: ttf.readUInt32BE(o + 8), length: ttf.readUInt32BE(o + 12) });
  }
  tables.sort((a, b) => Buffer.compare(a.tag, b.tag));
  let totalSfnt = 12 + 16 * numTables;
  const blobs = tables.map((t) => {
    const raw = ttf.subarray(t.offset, t.offset + t.length);
    totalSfnt += align4(t.length);
    const z = deflateSync(raw, { level: 9 });
    return z.length < raw.length ? z : raw;
  });
  const header = Buffer.alloc(44), dirBuf = Buffer.alloc(20 * numTables);
  let offset = 44 + 20 * numTables;
  const parts = [];
  tables.forEach((t, i) => {
    const d = i * 20;
    t.tag.copy(dirBuf, d); dirBuf.writeUInt32BE(offset, d + 4); dirBuf.writeUInt32BE(blobs[i].length, d + 8); dirBuf.writeUInt32BE(t.length, d + 12); dirBuf.writeUInt32BE(t.checksum, d + 16);
    const padded = Buffer.alloc(align4(blobs[i].length)); blobs[i].copy(padded);
    parts.push(padded); offset += padded.length;
  });
  header.write('wOFF', 0, 'ascii'); header.writeUInt32BE(ttf.readUInt32BE(0), 4); header.writeUInt32BE(offset, 8);
  header.writeUInt16BE(numTables, 12); header.writeUInt32BE(totalSfnt, 16); header.writeUInt16BE(1, 20); header.writeUInt16BE(0, 22);
  return Buffer.concat([header, dirBuf, ...parts]);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const faces = WEIGHTS.map(([weight, style]) => {
    const woff = ttfToWoff(readFileSync(join(dir, `Manrope-${style}.ttf`)));
    return `@font-face{font-family:"Manrope";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff;base64,${woff.toString('base64')}) format("woff")}`;
  });
  const css = ['/* Manrope 4.504, Copyright 2019 The Manrope Project Authors. SIL Open Font License 1.1: see ../LICENSE-fonts.txt.', '   Generated by tests/make-font-css.mjs. Embedded as data: URIs so no font files are fetched. */', ...faces, ''].join('\n');
  writeFileSync(join(root, 'site', 'css', 'fonts.css'), css);
  console.log(`Wrote site/css/fonts.css (${Math.round(css.length / 1024)} KB, weights ${WEIGHTS.map((w) => w[0]).join('/')})`);
}
